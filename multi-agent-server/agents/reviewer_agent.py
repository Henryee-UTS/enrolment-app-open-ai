import json
import os
from pathlib import Path
from typing import Any, Dict

from openai import OpenAI


# Locate the multi-agent-server directory and Reviewer prompt.
BASE_DIR = Path(__file__).resolve().parents[1]
PROMPT_PATH = BASE_DIR / "prompts" / "reviewer_prompt.txt"

# Connect to the local Ollama server.
OLLAMA_BASE_URL = os.getenv(
    "OLLAMA_BASE_URL",
    "http://localhost:11434/v1",
)

# The Reviewer uses Llama instead of the Worker's Qwen model.
OLLAMA_REVIEW_MODEL = os.getenv(
    "OLLAMA_REVIEW_MODEL",
    "llama3.1:8b",
)

# Read the request timeout from the environment.
OLLAMA_TIMEOUT_SECONDS = float(
    os.getenv("OLLAMA_TIMEOUT_SECONDS", "45")
)

# FAST_MODE reduces the default output token budget.
FAST_MODE = os.getenv("FAST_MODE", "true").lower() == "true"

REVIEWER_MAX_TOKENS = int(
    os.getenv(
        "REVIEWER_MAX_TOKENS",
        "160" if FAST_MODE else "400",
    )
)

# This Lab example leaves automatic retries at the client default.
client = OpenAI(
    base_url=OLLAMA_BASE_URL,
    api_key="ollama",
    timeout=OLLAMA_TIMEOUT_SECONDS,
    max_retries=0,
)


def load_prompt() -> str:
    """Read the Reviewer's instructions."""
    return PROMPT_PATH.read_text(encoding="utf-8").strip()


def call_model(
    user_request: str,
    worker_result: Dict[str, Any],
) -> str:
    """Ask the review model to examine the supplied Worker result."""

    # Serialize the complete Worker result as readable JSON.
    # Actual database evidence is available to the Reviewer only
    # if it is included in worker_result.
    #
    # Lab limitation:
    # The saved prompt requests 60 words, while this text says 160.
    prompt = f"""
{load_prompt()}

Constraints:
- Keep each section brief and actionable.
- Return only: Risk, Correction, Retest, Recommendation.
- Keep response under 60 words.

User Request:

{user_request}

Worker Result:

{json.dumps(worker_result, indent=2)}
"""

    try:
        response = client.chat.completions.create(
            model=OLLAMA_REVIEW_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": prompt,
                }
            ],
            temperature=0.1,
            max_tokens=REVIEWER_MAX_TOKENS,
        )

        # Extract the model's text.
        # This does not automatically verify review quality.
        return response.choices[0].message.content.strip()

    except Exception as exc:
        # Return a local fallback message if the model call fails.
        # This message is not a review generated by Llama.
        return (
            "Risk: Review model unavailable.\n"
            "Correction: Verify Ollama and reviewer model.\n"
            "Retest: Run the workflow again.\n"
            f"Recommendation: Do not approve until reviewed. Error: {exc}"
        )


def review_output(
    user_request: str,
    worker_result: Dict[str, Any],
) -> Dict[str, Any]:
    """Package the review for the Coordinator or standalone test."""

    # Lab limitation:
    # status remains "success" even if call_model returns fallback text.
    # Inspect the review field before claiming the model review succeeded.
    return {
        "status": "success",
        "agent": "reviewer_agent",
        "model": OLLAMA_REVIEW_MODEL,
        "review": call_model(user_request, worker_result),

        # Approval is required, but has not been granted here.
        "human_approval_required": True,
    }


if __name__ == "__main__":
    # This is the Lab's fixed sample, not a fresh Worker execution.
    # It contains a count and summary, but no underlying student records.
    sample_worker_result = {
        "status": "success",
        "subject_code": "ASD101",
        "evidence_count": 2,
        "output": "Two students are enrolled in ASD101.",
    }

    result = review_output(
        "Generate a student enrolment summary for ASD101.",
        sample_worker_result,
    )

    print(json.dumps(result, indent=2))